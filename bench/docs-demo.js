/** v1 과 수치 문장이 같은지 코드가 확인한다 — 눈으로 대조하지 않는다. */
export function numericSentencesOf(text) {
  return text.split('\n')
    .map((l) => l.replace(/^[◾✅\-•‣–]\s*/, '').trim())
    .filter((l) => /\d/.test(l))
}
